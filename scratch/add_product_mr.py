count = 0
for pid, info in product_mr_data.items():
    pattern = rf'(\s*id:\s*["\']{pid}["\'],)'
    match = re.search(pattern, code)
    if match:
        matched_str = match.group(1)
        features_json = json.dumps(info['featuresMr'], ensure_ascii=False, indent=6)
        # Format replacement
        replacement = f"""{matched_str}
    badgeMr: "{info['badgeMr']}",
    packagingMr: "{info['packagingMr']}",
    featuresMr: {features_json},"""
        code = code.replace(matched_str, replacement, 1)
        count += 1
    else:
        print(f"Could not find product id {pid}")

with open('js/data.js', 'w', encoding='utf-8') as f:
    f.write(code)

print(f"Successfully added Marathi fields to {count}/16 products in js/data.js!")

